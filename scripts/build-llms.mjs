#!/usr/bin/env node
/**
 * Builds the machine-readable copies of the product page in docs/:
 * - docs/llms-full.txt: docs/index.md, README.md and the Agent Skill in one file.
 * - the FAQPage JSON-LD in docs/index.html, from the visible FAQ section.
 *
 * Usage: node scripts/build-llms.mjs [--check]
 * --check writes nothing and fails if a generated part is stale, a docs/llms.txt
 * link into this repository names a missing file, or JSON-LD does not parse.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const path = (p) => resolve(root, p);
const read = (p) => readFileSync(path(p), "utf8").replace(/\r\n/g, "\n");
const check = process.argv.includes("--check");
const problems = [];

// llms-full.txt
const SOURCES = [
  ["docs/index.md", "The product page", "https://mxlo.top/agendar/"],
  ["README.md", "README", "https://github.com/Maolon/agendar/blob/main/README.md"],
  ["skills/agendar/SKILL.md", "Agent Skill", "https://github.com/Maolon/agendar/blob/main/skills/agendar/SKILL.md"],
];
const rule = "=".repeat(72);
let full = "# Agendar: full text for language models\n\n"
  + "> Generated by scripts/build-llms.mjs from the files below; do not edit by hand.\n"
  + "> Index: https://mxlo.top/agendar/llms.txt\n";
for (const [file, title, url] of SOURCES) {
  full += `\n${rule}\n${title}: ${file}\nSource: ${url}\n${rule}\n\n${read(file).trim()}\n`;
}

// FAQPage JSON-LD from the visible FAQ.
const decode = (s) => s.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"')
  .replace(/&#39;/g, "'").replace(/&nbsp;/g, " ").replace(/&amp;/g, "&");
const text = (html) => decode(html.replace(/<[^>]+>/g, "")).replace(/\s+/g, " ").trim();
let html = read("docs/index.html");
const faqSection = html.match(/<section[^>]*id="faq"[^>]*>([\s\S]*?)<\/section>/);
if (!faqSection) problems.push('docs/index.html has no <section id="faq">');
const qa = [...(faqSection?.[1] ?? "").matchAll(/<summary>([\s\S]*?)<\/summary>\s*<p>([\s\S]*?)<\/p>/g)]
  .map(([, q, a]) => ({ "@type": "Question", name: text(q), acceptedAnswer: { "@type": "Answer", text: text(a) } }));
if (faqSection && !qa.length) problems.push("the FAQ section has no <summary> + <p> pairs");
const faqLd = JSON.stringify({ "@context": "https://schema.org", "@type": "FAQPage", mainEntity: qa }, null, 2);
const faqBlock = `<script type="application/ld+json" id="faq-ld">\n${faqLd}\n</script>`;
const faqBlockRe = /<script type="application\/ld\+json" id="faq-ld">[\s\S]*?<\/script>/;
if (!faqBlockRe.test(html)) problems.push('docs/index.html has no <script type="application/ld+json" id="faq-ld"> block');
const builtHtml = html.replace(faqBlockRe, () => faqBlock);

// JSON-LD must parse.
for (const [, body] of builtHtml.matchAll(/<script type="application\/ld\+json"[^>]*>([\s\S]*?)<\/script>/g)) {
  try { JSON.parse(body); } catch (e) { problems.push(`JSON-LD in docs/index.html does not parse: ${e.message}`); }
}

// llms.txt links into this repository must name files that exist.
const llms = read("docs/llms.txt");
for (const [url] of llms.matchAll(/https:\/\/[^\s)>\]]+/g)) {
  let file = null;
  let m;
  if ((m = url.match(/^https:\/\/raw\.githubusercontent\.com\/Maolon\/agendar\/main\/(.+)$/))) file = m[1];
  else if ((m = url.match(/^https:\/\/mxlo\.top\/agendar\/(.*)$/))) file = `docs/${m[1] || "index.html"}`;
  // The file this script writes counts as present; --check catches it missing as stale.
  if (file && file !== "docs/llms-full.txt" && !existsSync(path(decodeURIComponent(file)))) problems.push(`docs/llms.txt links to ${url}, but ${file} does not exist`);
}

const fullPath = "docs/llms-full.txt";
if (check) {
  if (!existsSync(path(fullPath)) || read(fullPath) !== full) problems.push(`${fullPath} is stale`);
  if (builtHtml !== html) problems.push("the FAQPage JSON-LD in docs/index.html does not match the visible FAQ");
  if (problems.length && problems.some((p) => p.includes("stale") || p.includes("does not match"))) {
    problems.push("run `node scripts/build-llms.mjs` and commit the result");
  }
} else if (!problems.length) {
  writeFileSync(path(fullPath), full);
  if (builtHtml !== html) writeFileSync(path("docs/index.html"), builtHtml);
}

if (problems.length) {
  for (const p of problems) console.error(`error: ${p}`);
  process.exit(1);
}
console.log(check ? `ok: ${fullPath}, FAQ JSON-LD (${qa.length} questions) and docs/llms.txt links are current`
  : `wrote ${fullPath} and the FAQ JSON-LD (${qa.length} questions)`);
